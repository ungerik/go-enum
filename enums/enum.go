/*
Package enums provides enum detection, extraction, and code generation from Go AST.

It scans the Go source files of a package for types marked with the //#enum comment,
extracts all related information including enum values, methods,
and configuration flags, then generates type-safe validation and utility methods.

The main entry point is Rewrite, which processes Go packages and generates
enum methods by finding enum types (via Find), applying code generation templates,
and updating the files declaring the enum types with the generated methods.
*/
package enums

import (
	"go/ast"
	"go/token"
	"go/types"
	"slices"
)

// Enum represents a discovered enum type with all its metadata.
// It contains information about the enum type, its values, and configuration.
type Enum struct {
	// File is the path of the source file declaring the enum type,
	// where the generated methods are written
	File string
	// Line is the line number where the enum type is declared
	Line int
	// Package is the package name
	Package string
	// Type is the enum type name
	Type string
	// Underlying is the underlying type as written in the type declaration (e.g., "string", "int")
	Underlying string
	// Recv is the method receiver name (auto-generated or from existing methods)
	Recv string
	// Values are the valid values of the enum type ordered by file name and position
	Values []*Value
	// Null is the name of the null enum value (if //#null is used)
	Null string
	// JSONSchema indicates if ,jsonschema flag was set
	JSONSchema bool
	// CustomMethods names methods marked `//#custom` in their doc comment.
	// These are hand-written and must not be regenerated or replaced.
	// Keyed by the generator's method name (e.g. "UnmarshalJSON").
	CustomMethods map[string]bool

	// basic is the underlying basic type
	basic *types.Basic
	// underlyingName is the name of the underlying type without
	// type arguments, like j of j[int]
	underlyingName string
	// insertAfter is the declaration of the last enum const
	// in the file of the enum type, or the type declaration
	// if that file has no enum consts
	insertAfter ast.Decl
	// generated are the methods in the file of the enum type
	// that were generated by go-enum, in source order.
	// They are replaced by the generated methods
	// or removed if they are no longer generated.
	generated []*ast.FuncDecl
}

// Value is a valid value of an enum type.
type Value struct {
	// Name is the name of the const
	Name string
	// Pos is the position of the const name
	Pos token.Position
	// StringExpr is a Go expression of the value as string
	StringExpr string
	// JSONExpr is a Go expression of the value for the JSON Schema enum
	JSONExpr string
	// Null indicates the null value marked with //#null
	Null bool
}

// basicType returns the basic underlying type, also for an Enum that
// was not returned by Find and has a predeclared Underlying type.
func (e *Enum) basicType() *types.Basic {
	if e.basic != nil {
		return e.basic
	}
	if obj, ok := types.Universe.Lookup(e.Underlying).(*types.TypeName); ok {
		if basic, ok := obj.Type().(*types.Basic); ok {
			return basic
		}
	}
	return types.Typ[types.Invalid]
}

// IsStringType returns true if the underlying type is string.
func (e *Enum) IsStringType() bool {
	return e.basicType().Info()&types.IsString != 0
}

// IsIntType returns true if the underlying type is an integer type.
func (e *Enum) IsIntType() bool {
	return e.basicType().Info()&types.IsInteger != 0
}

// IsNullable returns true if the enum has a null value defined.
func (e *Enum) IsNullable() bool {
	return e.Null != ""
}

// LastIndex returns the index of the last enum value.
func (e *Enum) LastIndex() int {
	return len(e.Values) - 1
}

// JSONType returns the JSON Schema type for this enum's underlying type.
func (e *Enum) JSONType() string {
	switch info := e.basicType().Info(); {
	case info&types.IsNumeric != 0:
		return "number"
	case info&types.IsBoolean != 0:
		return "boolean"
	default:
		return "string"
	}
}

// Param returns name for a parameter of a generated method, or alternative,
// with _ appended until it is unused, if name is already used as receiver
// name, type name or enum value.
func (e *Enum) Param(name, alternative string) string {
	used := func(candidate string) bool {
		return candidate == e.Recv || candidate == e.Type || candidate == e.underlyingName ||
			slices.ContainsFunc(e.Values, func(v *Value) bool { return v.Name == candidate })
	}
	if !used(name) {
		return name
	}
	for used(alternative) {
		alternative += "_"
	}
	return alternative
}
